/** Every character the font draws; `~` is a solid block (the cursor). */
export const PIXEL_CHARS = Object.keys(G).join('');

/** Map any text onto the font: upper case, en/em dashes to `-`, anything unknown to `?`. */
export function pixelSafe(text: string): string {
  return [...text.toUpperCase().replace(/[–—]/g, '-').replace(/…/g, '...')]
    .map(ch => ch === '\n' || G[ch] ? ch : '?').join('');
}

/** Build the font texture and register it once per game (Boot calls this before anything draws text). */
export function registerPixelFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.exists(PIXEL_FONT)) return;
  const key = `${PIXEL_FONT}-glyphs`;
  if (!scene.textures.exists(key)) {
    const canvas = scene.textures.createCanvas(key, PIXEL_CHARS.length * GLYPH.w, GLYPH.h);
    if (!canvas) return;
    const ctx = canvas.context;
    ctx.fillStyle = '#ffffff';
    [...PIXEL_CHARS].forEach((ch, i) => G[ch].split('|').forEach((row, y) => [...row].forEach((bit, x) => {
      if (bit === '#') ctx.fillRect(i * GLYPH.w + x, y, 1, 1);
    })));
    canvas.refresh();
  }
  scene.cache.bitmapFont.add(PIXEL_FONT, Phaser.GameObjects.RetroFont.Parse(scene, {
    image: key, width: GLYPH.w, height: GLYPH.h, chars: PIXEL_CHARS, charsPerRow: PIXEL_CHARS.length,
    'spacing.x': 0, 'spacing.y': 0, 'offset.x': 0, 'offset.y': 0, lineSpacing: 2,
  }));
}

/** Pixel text at an integer scale, tinted. `scale` 2 → 12 px per character. */
export function pixelText(scene: Phaser.Scene, x: number, y: number, text: string, scale = 2, tint = 0xe8e4dc) {
  return scene.add.bitmapText(x, y, PIXEL_FONT, pixelSafe(text)).setScale(Math.max(1, Math.round(scale))).setTint(tint);
}
